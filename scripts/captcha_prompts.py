# 验证码类型检测提示词
captcha_detection_prompt = """
请分析这个屏幕截图，识别其中的验证码类型。可能的类型包括：
1. 文本验证码：显示字母或数字组合，需要用户输入识别结果
2. 滑块验证码：需要拖动滑块到指定位置完成验证
3. 点击验证码：需要点击特定图片或区域，如"请点击所有的汽车"
4. 数学验证码：显示数学表达式，需要计算结果并输入
5. 其他类型：如果不属于上述类型，请详细描述

请仔细观察图像中的所有元素，包括文本指示、输入框、滑块、图片网格等特征。
回答格式：
验证码类型：[类型名称]
特征描述：[简要描述验证码的主要特征和识别依据]
"""

# 文本验证码识别提示词
text_captcha_prompt = """
请识别图片中的文本验证码。这是一个需要精确识别的任务。

请注意以下几点：
1. 验证码通常是4-6位的字母或数字组合
2. 可能存在干扰线、噪点、变形或扭曲的字符
3. 字符可能有重叠或连接
4. 背景可能有干扰图案

识别策略：
- 首先整体观察验证码区域，确定字符数量
- 从左到右依次识别每个字符
- 区分容易混淆的字符，如0和O、1和I、5和S、8和B等
- 如果某个字符不确定，可以根据上下文或常见验证码模式推测

请直接回答识别出的验证码文本，格式：
验证码：XXXX
"""

# 滑块验证码处理提示词
slider_captcha_prompt = """
请仔细观察这张图片中的滑块验证码，并详细描述你看到的内容。

重要识别要点：
1. 滑块验证码通常包含一个主要的拼图背景图和一个可拖动的小拼图块
2. 滑块按钮（拖动控制）一般位于被拖动图片的正下方很近的位置
3. 滑块按钮通常是圆形或方形的按钮，可能有箭头图标
4. 缺口位置在主背景图中，形状与被拖动的小图块匹配

请按以下格式详细回答：

验证码类型：[描述这是什么类型的滑块验证码，如拼图滑块、文字滑块等]

主背景图描述：[描述主要的背景拼图图片，包括内容和大致位置]

被拖动图片：[描述需要被拖动的小图片块，通常在主图的左侧或单独显示]

滑块按钮位置：[重点描述拖动控制按钮的位置，特别注意是否在被拖动图片的正下方附近。请估算按钮在整个屏幕中的大致位置，如"位于屏幕左侧约1/6处，垂直位置约3/4处"]

缺口位置：[详细描述主背景图中缺口的具体位置。请尽量给出相对于整个图片的位置估算，如"位于主背景图的右侧约3/4处，垂直位置约中间偏上，大约1/3处"或"在图片右半部分靠近中央位置"]

操作说明：[根据你的观察，说明应该如何操作这个验证码]

请特别注意：
- 滑块按钮通常就在需要拖动的图片块的正下方很近的地方
- 缺口位置的描述要尽量精确，包括水平和垂直的相对位置
- 如果能看到明显的位置特征，请详细描述
"""

# 点击验证码处理提示词
click_captcha_prompt = """
请分析这个点击验证码，识别需要点击的目标对象。

分析要点：
1. 验证码的指令文本（如"请点击所有的公交车"）
2. 图片网格中符合条件的所有目标
3. 每个目标的精确坐标位置

识别策略：
- 仔细阅读指令，明确点击目标的类别
- 逐一扫描图片网格中的每个单元
- 对于模糊或部分可见的目标，也需要判断是否符合条件
- 有些验证码可能需要按特定顺序点击，注意相关提示

请提供需要点击的坐标位置，格式：
指令要求：[复述指令内容]
点击位置：(x1,y1), (x2,y2), ...
点击顺序：[如有特殊要求]
"""

